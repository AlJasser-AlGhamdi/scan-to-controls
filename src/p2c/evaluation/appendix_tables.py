def _header(name: str, source: str) -> str:
    return (
        f"% {name}: generated by scripts/build_appendix_tables.py from\n"
        f"%   {source}\n"
        "% Do not edit by hand. paper/verify_numbers.py compares this file byte for byte\n"
        "% against the generator's output and fails on any difference.\n"
    )


def _tex_check(value: str) -> str:
    return "\\texttt{" + value.replace("_", "\\_") + "}"


def provenance(sensitivity: float, false_alarm: float) -> str:
    if false_alarm == 0.0:
        return "deterministic read"
    if sensitivity >= DETERMINISTIC_MIN:
        return "high reliability probe"
    return "author judgment"


def render_rates_table() -> str:
    from p2c.evaluation.synthetic import _APEX_ONLY_CHECKS, _ORIGIN_CHECKS, _SUBSET_PROB, FALSE_ALARM, SENSITIVITY
    from p2c.scanning.catalog import LIVE_CHECKS

    def site(check):
        return "apex" if check in _APEX_ONLY_CHECKS else ("origin" if check in _ORIGIN_CHECKS else "edge")

    short = {"deterministic read": "read", "high reliability probe": "probe", "author judgment": "judgement"}
    blocks = []
    for label in ("deterministic read", "high reliability probe", "author judgment"):
        blocks.append(
            "\n".join(
                f"{_tex_check(check.value)} & {SENSITIVITY[check]:.2f} & {FALSE_ALARM[check]:.2f} & "
                f"{_SUBSET_PROB[check]:.2f} & {site(check)} & {short[label]} & {'yes' if check in LIVE_CHECKS else 'no'} \\\\"
                for check in SENSITIVITY
                if provenance(SENSITIVITY[check], FALSE_ALARM[check]) == label
            )
        )
    rows = "\n\\addlinespace\n".join(blocks)
    caption = (
        f"Modelled detection rates for the {len(SENSITIVITY)} detectors. Sens.: sensitivity. FP: false-positive "
        "rate per host (per firm for the detectors read at the apex). Draw: the probability $p_k$ of Algorithm~\\ref{alg:generator} that the detector's issue "
        "is drawn once its category is. Site: where the sensing model reads the detector (the origin server, the "
        "CDN edge or the apex domain). Provenance: deterministic read, high-reliability probe or analyst judgement. "
        "Live: the released toolkit has a live inspector."
    )
    source = "p2c.evaluation.synthetic (SENSITIVITY, FALSE_ALARM) + p2c.scanning.catalog.LIVE_CHECKS"
    return f"""{_header("tab_rates.tex", source)}% [!htbp], not [tbp]: without h the table can only reach the top of a column, and on the
% appendix page it floated above the Appendix A heading that introduces it, so a reader met
% the table before the section. h places it under its own paragraph and the page still holds.
\\begin{{table}}[!htbp]
\\centering
\\caption{{{caption}}}
\\label{{tab:rates}}
\\scriptsize
\\setlength{{\\tabcolsep}}{{2.5pt}}
\\begin{{tabular}}{{@{{}}l S[table-format=1.2] S[table-format=1.2] S[table-format=1.2] l l l@{{}}}}
\\toprule
Detector & {{Sens.}} & {{FP}} & {{Draw}} & Site & Provenance & Live \\\\
\\midrule
{rows}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def _panel(title: str) -> str:
    return f"\\multicolumn{{3}}{{@{{}}l}}{{\\emph{{{title}}}}} \\\\"


def render_priors_table() -> str:
    from p2c.evaluation import synthetic as syn

    bands = {b.name: b for b in syn.SIZE_BANDS}
    lines: list[str] = []

    lines.append(_panel("Firm size bands, share of Class B"))
    for name in ("small", "medium"):
        band = bands[name]
        label = f"{name.capitalize()}, apex plus {band.min_subs} to {band.max_subs} subdomains"
        lines.append(f"{label} & {band.share:.2f} & Monsha'at Q4 2023 \\\\")

    lines.append("\\addlinespace")
    lines.append(_panel("Security posture, share of the size band"))
    for band_name in ("small", "medium"):
        shares = bands[band_name].posture_shares
        for posture in ("strong", "moderate", "weak"):
            label = f"{_POSTURE_LABEL[posture]}, {band_name} firm"
            lines.append(f"{label} & {shares[posture]:.2f} & declared \\\\")

    lines.append("\\addlinespace")
    lines.append(_panel("Posture multiplier"))
    for posture in ("strong", "moderate", "weak"):
        lines.append(f"{_POSTURE_LABEL[posture]} & {syn.POSTURE_MULT[posture]:.2f} & declared \\\\")

    lines.append("\\addlinespace")
    lines.append(_panel("Sector prevalence"))
    for sector in syn.SECTORS:
        label, src = _SECTOR_LABEL[sector.name], _SECTOR_SOURCE[sector.name]
        lines.append(f"{label} & {sector.prevalence:.2f} & {src} \\\\")

    lines.append("\\addlinespace")
    lines.append(_panel("Domain TLD weight"))
    for tld in syn._TLDS:
        lines.append(f"\\texttt{{{tld}}} & {syn._TLD_WEIGHTS[tld]:.2f} & declared \\\\")

    lines.append("\\addlinespace")
    lines.append(_panel("Evidence model, on the externally testable and attestation-required rows"))
    coverage = syn.OFF_SURFACE_COVERAGE
    for label, value in (
        ("Declare a clean control", syn.P_ATTEST_CLEAN),
        ("Overstate a violated control", syn.P_OVERSTATE),
        ("Declaration expired at the assessment date", syn.P_ATTEST_EXPIRED),
        ("Declaration not yet effective", syn.P_ATTEST_NOT_YET),
        ("Attestation-required rows with evidence, strong firm", coverage["strong"]),
        ("Attestation-required rows with evidence, moderate firm", coverage["moderate"]),
        ("Attestation-required rows with evidence, weak firm", coverage["weak"]),
        ("Internal assessment finds a gap", syn.P_INTERNAL_GAP),
    ):
        lines.append(f"{label} & {value:.2f} & declared \\\\")

    body = "\n".join(lines)
    caption = (
        "Generator population priors with their sources."
    )
    source = (
        "p2c.evaluation.synthetic (SIZE_BANDS, SECTORS, POSTURE_MULT, TLD weights, "
        "P_ATTEST_*, OFF_SURFACE_COVERAGE, P_INTERNAL_GAP); sources dataset/sources/SOURCES.md"
    )
    return f"""{_header("tab_priors.tex", source)}% [!htbp] for the reason given above tab_rates: [tbp] floated this above the appendix
% heading that introduces it.
\\begin{{table}}[!htbp]
\\centering
\\caption{{{caption}}}
\\label{{tab:priors}}
\\scriptsize
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{@{{}}l S[table-format=1.2] l@{{}}}}
\\toprule
Parameter & {{Value}} & Source \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


